(function () {
  // Skip the glossary page itself
  if (document.querySelector('.glossary-term')) return;
  if (typeof GLOSSARY_TERMS === 'undefined' || !Array.isArray(GLOSSARY_TERMS)) return;
  var glossOff = document.body && document.body.getAttribute('data-gloss') === 'off';

  var EXCLUDE_SINGLE = { 'inside': 1, 'outside': 1, 'bridge': 1, 'space': 1, 'time': 1 };

  function esc(s) { return s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'); }

  var multi = [], single = [];
  GLOSSARY_TERMS.forEach(function (t) {
    var words = t.name.trim().split(/\s+/).length;
    if (words > 1 || t.name.indexOf('-') !== -1) multi.push(t);
    else if (!EXCLUDE_SINGLE[t.name.toLowerCase()]) single.push(t);
  });
  // longest names first so "New Potential" wins over "Potential"
  function byLen(a, b) { return b.name.length - a.name.length; }
  multi.sort(byLen); single.sort(byLen);

  var multiRe = new RegExp('\\b(' + multi.map(function (t) { return esc(t.name); }).join('|') + ')\\b', 'gi');
  var singleRe = new RegExp('\\b(' + single.map(function (t) { return esc(t.name); }).join('|') + ')\\b', 'gi');

  var byName = {};
  GLOSSARY_TERMS.forEach(function (t) { byName[t.name.toLowerCase()] = t; });

  function wrapMatches(root, regex) {
    var walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
      acceptNode: function (node) {
        var p = node.parentElement;
        if (!p) return NodeFilter.FILTER_REJECT;
        if (p.closest('.gloss-term, a, h1, h2, h3, button, .audio-caption, figcaption, #discussion, header, nav, footer, script, style')) return NodeFilter.FILTER_REJECT;
        if (!node.nodeValue || !node.nodeValue.trim()) return NodeFilter.FILTER_REJECT;
        return NodeFilter.FILTER_ACCEPT;
      }
    });
    var nodes = [];
    while (walker.nextNode()) nodes.push(walker.currentNode);
    nodes.forEach(function (node) {
      var text = node.nodeValue, out = [], last = 0, m;
      regex.lastIndex = 0;
      var frag = null;
      while ((m = regex.exec(text)) !== null) {
        var term = byName[m[1].toLowerCase()];
        if (!term) continue;
        if (!frag) frag = document.createDocumentFragment();
        out.push(document.createTextNode(text.slice(last, m.index)));
        var b = document.createElement('span');
        b.className = 'gloss-term';
        b.setAttribute('role', 'button');
        b.setAttribute('tabindex', '0');
        b.textContent = m[1];
        b.setAttribute('data-term-id', term.id);
        b.setAttribute('aria-label', term.name + ': show definition');
        out.push(b);
        last = m.index + m[0].length;
      }
      if (frag) {
        out.push(document.createTextNode(text.slice(last)));
        out.forEach(function (n) { frag.appendChild(n); });
        node.parentNode.replaceChild(frag, node);
      }
    });
  }

  if (!glossOff) {
    var scope = document.querySelector('main') || document.body;
    // ---- compound: "spacetime"/"space-time" -> separate Space + Time highlights ----
    var spaceTerm = null, timeTerm = null;
    GLOSSARY_TERMS.forEach(function (t) {
      if (t.id === 'term-space') spaceTerm = t;
      if (t.id === 'term-time') timeTerm = t;
    });
    function mkGlossSpan(text, term) {
      var b = document.createElement('span');
      b.className = 'gloss-term';
      b.setAttribute('role', 'button');
      b.setAttribute('tabindex', '0');
      b.textContent = text;
      b.setAttribute('data-term-id', term.id);
      b.setAttribute('aria-label', term.name + ': show definition');
      return b;
    }
    function wrapSpacetime(root) {
      if (!spaceTerm || !timeTerm) return;
      var re = /\bspace[-\u2013\u2014]?time\b/gi;
      var walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
        acceptNode: function (node) {
          var p = node.parentElement;
          if (!p) return NodeFilter.FILTER_REJECT;
          if (p.closest('.gloss-term, a, h1, h2, h3, button, .audio-caption, figcaption, #discussion, header, nav, footer, script, style')) return NodeFilter.FILTER_REJECT;
          if (!node.nodeValue || !node.nodeValue.trim()) return NodeFilter.FILTER_REJECT;
          return NodeFilter.FILTER_ACCEPT;
        }
      });
      var nodes = [];
      while (walker.nextNode()) nodes.push(walker.currentNode);
      nodes.forEach(function (node) {
        var text = node.nodeValue, m, last = 0, frag = null, out = [];
        re.lastIndex = 0;
        while ((m = re.exec(text)) !== null) {
          var m0 = m[0], si = m0.search(/[-\u2013\u2014]/), spT, sep, tiT;
          if (si === -1) { spT = m0.slice(0, 5); sep = ''; tiT = m0.slice(5); }
          else { spT = m0.slice(0, si); sep = m0[si]; tiT = m0.slice(si + 1); }
          if (!frag) frag = document.createDocumentFragment();
          out.push(document.createTextNode(text.slice(last, m.index)));
          out.push(mkGlossSpan(spT, spaceTerm));
          if (sep) out.push(document.createTextNode(sep));
          out.push(mkGlossSpan(tiT, timeTerm));
          last = m.index + m0.length;
        }
        if (frag) {
          out.push(document.createTextNode(text.slice(last)));
          out.forEach(function (n) { frag.appendChild(n); });
          node.parentNode.replaceChild(frag, node);
        }
      });
    }
    wrapSpacetime(scope);
    wrapMatches(scope, multiRe);
    wrapMatches(scope, singleRe);
  }

  // ---- popup ----
  if (!glossOff) {
    var popup = document.createElement('div');
    popup.id = 'gloss-popup';
    popup.hidden = true;
    popup.innerHTML = '<button class="gloss-close" aria-label="Close definition">&times;</button>' +
      '<p class="gloss-name"></p><p class="gloss-def"></p>' +
      '<a class="gloss-link" href="glossary.html">Framework Glossary &rarr;</a>';
    document.body.appendChild(popup);
    var popName = popup.querySelector('.gloss-name'),
        popDef = popup.querySelector('.gloss-def'),
        popLink = popup.querySelector('.gloss-link');
    function hide() { popup.hidden = true; }
    popup.querySelector('.gloss-close').addEventListener('click', function (e) { e.stopPropagation(); hide(); });
    document.addEventListener('click', function (e) {
      if (!popup.hidden && !popup.contains(e.target) && !e.target.closest('.gloss-term')) hide();
    });
    document.addEventListener('keydown', function (e) { if (e.key === 'Escape') hide(); });
    document.addEventListener('scroll', hide, { passive: true, capture: true });
    function showTerm(el) {
      var term = null;
      var tid = el.getAttribute('data-term-id');
      for (var i = 0; i < GLOSSARY_TERMS.length; i++) {
        if (GLOSSARY_TERMS[i].id === tid) { term = GLOSSARY_TERMS[i]; break; }
      }
      if (!term) return;
      popName.textContent = term.name;
      popDef.textContent = term.def;
      popLink.href = 'glossary.html#' + term.id;
      popup.hidden = false;
      var r = el.getBoundingClientRect();
      var pw = popup.offsetWidth, ph = popup.offsetHeight;
      var x = r.left + r.width / 2 - pw / 2;
      x = Math.max(12, Math.min(x, window.innerWidth - pw - 12));
      var y = r.bottom + 10;
      if (y + ph > window.innerHeight - 12) y = r.top - ph - 10;
      if (y < 12) y = 12;
      popup.style.left = x + 'px';
      popup.style.top = y + 'px';
    }
    document.addEventListener('click', function (e) {
      var el = e.target.closest('.gloss-term');
      if (!el) return;
      e.stopPropagation();
      showTerm(el);
    });
    document.addEventListener('keydown', function (e) {
      var el = e.target && e.target.closest ? e.target.closest('.gloss-term') : null;
      if (el && (e.key === 'Enter' || e.key === ' ')) { e.preventDefault(); showTerm(el); }
    });
  }

})();
